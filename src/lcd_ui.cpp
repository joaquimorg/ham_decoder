static inline uint16_t rgb565(int r, int g, int b)
{
    return (uint16_t)(((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3));
}

// Waterfall palette, as on the web page: black, blue, cyan, yellow, red, white.
static void build_lut()
{
    static const uint8_t stops[][3] = {
        {0, 0, 0}, {0, 0, 200}, {0, 200, 220}, {240, 240, 0}, {240, 0, 0}, {255, 255, 255},
    };
    const int n = sizeof(stops) / sizeof(stops[0]) - 1;
    for (int i = 0; i < 256; i++) {
        const float p = i / 255.0f * n;
        const int k = p >= n ? n - 1 : (int)p;
        const float f = p - k;
        wf_lut[i] = rgb565(stops[k][0] + (stops[k + 1][0] - stops[k][0]) * f,
                           stops[k][1] + (stops[k + 1][1] - stops[k][1]) * f,
                           stops[k][2] + (stops[k + 1][2] - stops[k][2]) * f);
    }
}

static float col_hz(int col)
{
    return (col + 0.5f) * UI_BINS / LCD_H_RES * DSP_SAMPLE_RATE / FFT_SIZE;
}

static int hz_col(float hz)
{
    return (int)(hz * FFT_SIZE / DSP_SAMPLE_RATE * LCD_H_RES / UI_BINS);
}

static lv_obj_t *make_canvas(lv_obj_t *parent, uint16_t **buf, int w, int h)
{
    if (!*buf)    // kept across rebuilds (language change)
        *buf = (uint16_t *)heap_caps_calloc(w * h, sizeof(uint16_t), MALLOC_CAP_SPIRAM);
    lv_obj_t *c = lv_canvas_create(parent);
    lv_canvas_set_buffer(c, *buf, w, h, LV_COLOR_FORMAT_RGB565);
    return c;
}

