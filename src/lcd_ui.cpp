// Level byte: 0.5 dB steps from -120 dBFS. The colour scale follows the noise
// floor (20th percentile of each row, smoothed) and spans WF_SPAN.
#define WF_SPAN  100    // 50 dB
static float wf_floor = -1.0f;

static void draw_rows(const uint8_t (*rows)[UI_BINS], int n)
{
    for (int r = 0; r < n; r++) {
        const uint8_t *row = rows[r];
        uint16_t hist[256] = {};
        for (int i = 0; i < UI_BINS; i++)
            hist[row[i]]++;
        int q = 0;
        for (int acc = 0; q < 255 && (acc += hist[q]) < UI_BINS / 5; q++) {}
        wf_floor = wf_floor < 0.0f ? q : wf_floor + (q - wf_floor) * 0.05f;
        const int lo = (int)wf_floor - 6;

        memmove(wf_buf + LCD_H_RES, wf_buf, LCD_H_RES * (WF_H - 1) * sizeof(uint16_t));
        for (int c = 0; c < LCD_H_RES; c++) {
            int v = (row[c * UI_BINS / LCD_H_RES] - lo) * 255 / WF_SPAN;
            wf_buf[c] = wf_lut[v < 0 ? 0 : v > 255 ? 255 : v];
        }
    }
    if (!n)
        return;

    // Spectrum of the newest row, with a 500 Hz grid and the decoder tones.
    const uint8_t *row = rows[n - 1];
    const int lo = (int)wf_floor - 6;
    const uint16_t bg = rgb565(8, 12, 24), grid = rgb565(40, 48, 70), bar = rgb565(80, 200, 120);
    for (int i = 0; i < LCD_H_RES * SPEC_H; i++)
        spec_buf[i] = bg;
    for (int hz = 500; col_hz(LCD_H_RES - 1) > hz; hz += 500) {
        const int c = hz_col(hz);
        for (int y = 0; y < SPEC_H; y++)
            spec_buf[y * LCD_H_RES + c] = grid;
    }
    for (int c = 0; c < LCD_H_RES; c++) {
        int h = (row[c * UI_BINS / LCD_H_RES] - lo) * SPEC_H / WF_SPAN;
        h = h < 0 ? 0 : h > SPEC_H ? SPEC_H : h;
        for (int y = SPEC_H - h; y < SPEC_H; y++)
            spec_buf[y * LCD_H_RES + c] = bar;
    }
    auto marker = [](float hz, uint16_t color) {
        const int c = hz_col(hz);
        if (hz > 0.0f && c >= 0 && c < LCD_H_RES)
            for (int y = 0; y < SPEC_H; y += 2)
                spec_buf[y * LCD_H_RES + c] = color;
    };
    marker(last_status.tone_hz, rgb565(255, 60, 60));
    if (last_status.rtty_active) {
        marker(last_status.rtty_mark_hz, rgb565(255, 220, 0));
        marker(last_status.rtty_space_hz, rgb565(255, 220, 0));
    }
    if (!g_settings.cw_auto_tone)
        marker(g_settings.cw_tone_hz, rgb565(255, 255, 255));

    lv_obj_invalidate(spec_canvas);
    lv_obj_invalidate(wf_canvas);
}

// Tap on the spectrum/waterfall: manual CW tone there; long press: automatic.
static void spectrum_event(lv_event_t *e)
{
    lv_obj_t *obj = (lv_obj_t *)lv_event_get_target(e);
    if (lv_event_get_code(e) == LV_EVENT_LONG_PRESSED) {
        g_settings.cw_auto_tone = true;
    } else {
        lv_point_t p;
        lv_indev_get_point(lv_indev_active(), &p);
        lv_area_t a;
        lv_obj_get_coords(obj, &a);
        const float hz = col_hz(p.x - a.x1);
        if (hz < SPECTRUM_MIN_HZ || hz > SPECTRUM_MAX_HZ)
            return;
        g_settings.cw_auto_tone = false;
        g_settings.cw_tone_hz = hz;
    }
    settings_save();
}

