static void update_cfg_info()
{
    const WebNetInfo net = web_net_info();
    const float fs = analyzer_sample_rate();
    char s[320];
    snprintf(s, sizeof(s), "Wi-Fi: %s%s\n%s: %s\n%s: %s (%s: %u)\n%s: %.0f %%   %s: %u KB   Fs: %+.0f ppm",
             !net.started ? tr(S_WIFI_OFF) : net.connected ? net.ip : tr(S_WIFI_JOINING),
             net.ap ? tr(S_WIFI_AP) : "",
             tr(S_INFO_NET), g_settings.wifi_ssid[0] ? g_settings.wifi_ssid : tr(S_NET_NONE),
             tr(S_INFO_BOOT), boot_reason_text(), tr(S_INFO_RESETS), ui_boot_resets(),
             tr(S_INFO_LOAD), ui_load() * 100.0f, tr(S_INFO_RAM), (unsigned)(esp_get_free_heap_size() / 1024),
             fs > 0.0f ? (fs / DSP_SAMPLE_RATE - 1.0f) * 1e6f : 0.0f);
    lv_label_set_text(lbl_cfg_info, s);
    // The tone may change from the waterfall or the web page.
    if (g_settings.cw_auto_tone != lv_obj_has_state(sw_cw_auto, LV_STATE_CHECKED))
        lv_obj_set_state(sw_cw_auto, LV_STATE_CHECKED, g_settings.cw_auto_tone);
}

