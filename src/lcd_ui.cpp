        lv_obj_set_style_text_color(l, color, 0);
        lv_obj_set_width(l, lv_pct(100));
        lv_label_set_long_mode(l, LV_LABEL_LONG_MODE_WRAP);
        lv_obj_align(l, LV_ALIGN_BOTTOM_LEFT, 0, 0);
