static int index_of_float(const float *v, int n, float x)
{
    for (int i = 0; i < n; i++)
        if (x > v[i] - 0.01f && x < v[i] + 0.01f)
            return i;
    return 0;
}

static int index_of_int(const int *v, int n, int x)
{
    for (int i = 0; i < n; i++)
        if (v[i] == x)
            return i;
    return 0;
}

