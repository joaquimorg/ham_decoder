// Image (FAX / SSTV)

// FAX (grey) by default: full width, newest lines at the bottom (a long
// chart scrolls up). SSTV (colour, short) by default: the whole image. A tap
// swaps the two views.
static bool img_swap = false;
static uint32_t img_drawn_id = 0, img_drawn_lines = 0;
static int64_t img_drawn_us = 0;

static void render_image(bool force)
{
    const UiImageInfo info = ui_get_image_info();
    char s[96];
    if (!info.id || !info.width) {
        lv_label_set_text(lbl_img_info, tr(S_IMG_NONE));
        return;
    }
    snprintf(s, sizeof(s), "%s  %u %s  %s", info.title, (unsigned)info.lines, tr(S_IMG_LINES),
             info.active ? tr(S_IMG_RECEIVING) : "");
    lv_label_set_text(lbl_img_info, s);

    const int64_t now = esp_timer_get_time();
    if (!force && info.id == img_drawn_id &&
        (info.lines == img_drawn_lines || now - img_drawn_us < 500000))
        return;

    const uint32_t held = info.lines - info.first;
    const float aspect = info.aspect > 0.0f ? info.aspect : 1.0f;
    for (int i = 0; i < LCD_H_RES * IMG_H; i++)
        img_buf[i] = 0;
    if (held > 0) {
        float scale;
        uint32_t first = info.first;
        const bool scroll = (info.channels == 1) != img_swap;
        if (scroll) {
            scale = (float)LCD_H_RES / info.width;
            const uint32_t fit = (uint32_t)(IMG_H / (aspect * scale));
            if (held > fit)
                first = info.lines - fit;
        } else {
            const float sw = (float)LCD_H_RES / info.width, sh = IMG_H / (held * aspect);
            scale = sw < sh ? sw : sh;
        }
        const int out_w = (int)(info.width * scale);
        const int out_h = (int)((info.lines - first) * aspect * scale);
        const int x0 = (LCD_H_RES - out_w) / 2;
        static uint8_t line[UI_IMG_MAX_LINE];
        uint32_t loaded = UINT32_MAX;
        for (int y = 0; y < out_h && y < IMG_H; y++) {
            const uint32_t k = first + (uint32_t)(y / (aspect * scale));
            if (k >= info.lines)
                break;
            if (k != loaded) {
                if (!ui_get_image_lines(info.id, k, 1, line))
                    return;    // changed meanwhile: next time
                loaded = k;
            }
            uint16_t *dst = img_buf + y * LCD_H_RES + x0;
            for (int x = 0; x < out_w; x++) {
                const int sx = (int)(x / scale);
                if (info.channels == 3) {
                    const uint8_t *p = line + sx * 3;
                    dst[x] = rgb565(p[0], p[1], p[2]);
                } else {
                    const uint8_t g = line[sx];
                    dst[x] = rgb565(g, g, g);
                }
            }
        }
    }
    img_drawn_id = info.id;
    img_drawn_lines = info.lines;
    img_drawn_us = now;
    lv_obj_invalidate(img_canvas);
}

static void image_event(lv_event_t *)
{
    img_swap = !img_swap;
    render_image(true);
}

