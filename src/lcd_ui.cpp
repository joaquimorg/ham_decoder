static void touch_init()
{
    i2c_master_bus_config_t bus = {};
    bus.i2c_port = I2C_NUM_0;
    bus.sda_io_num = (gpio_num_t)BOARD_I2C_SDA;
    bus.scl_io_num = (gpio_num_t)BOARD_I2C_SCL;
    bus.clk_source = I2C_CLK_SRC_DEFAULT;
    bus.glitch_ignore_cnt = 7;
    bus.flags.enable_internal_pullup = true;    // external 10 k are fitted too
    ESP_ERROR_CHECK(i2c_new_master_bus(&bus, &i2c_bus));

    gpio_config_t io = {};
    io.pin_bit_mask = 1ULL << TOUCH_PIN_RST;
    io.mode = GPIO_MODE_OUTPUT;
    gpio_config(&io);
    gpio_set_level((gpio_num_t)TOUCH_PIN_RST, 0);
    vTaskDelay(pdMS_TO_TICKS(10));
    gpio_set_level((gpio_num_t)TOUCH_PIN_RST, 1);
    vTaskDelay(pdMS_TO_TICKS(300));

    i2c_device_config_t dev = {};
    dev.dev_addr_length = I2C_ADDR_BIT_LEN_7;
    dev.device_address = TOUCH_ADDR;
    dev.scl_speed_hz = 400000;
    ESP_ERROR_CHECK(i2c_master_bus_add_device(i2c_bus, &dev, &touch_dev));
    if (i2c_master_probe(i2c_bus, TOUCH_ADDR, 50) != ESP_OK)
        ESP_LOGW(TAG, "touch (FT6336U, 0x%02x) nao responde", TOUCH_ADDR);
}

// LVGL input device: polls the FT6336U (TD_STATUS and the first point).
static void touch_read_cb(lv_indev_t *, lv_indev_data_t *data)
{
    static int16_t last_x = 0, last_y = 0;
    uint8_t reg = 0x02, b[5];
    data->state = LV_INDEV_STATE_RELEASED;
    if (i2c_master_transmit_receive(touch_dev, &reg, 1, b, sizeof(b), 20) == ESP_OK && (b[0] & 0x0F) > 0) {
        int x = ((b[1] & 0x0F) << 8) | b[2];
        int y = ((b[3] & 0x0F) << 8) | b[4];
        const int rx = x, ry = y;
#if TOUCH_SWAP_XY
        const int t = x; x = y; y = t;
#endif
#if TOUCH_MIRROR_X
        x = LCD_H_RES - 1 - x;
#endif
#if TOUCH_MIRROR_Y
        y = LCD_V_RES - 1 - y;
#endif
        last_x = x < 0 ? 0 : x >= LCD_H_RES ? LCD_H_RES - 1 : x;
        last_y = y < 0 ? 0 : y >= LCD_V_RES ? LCD_V_RES - 1 : y;
        data->state = LV_INDEV_STATE_PRESSED;
        if (TOUCH_DEBUG)
            ESP_LOGW(TAG, "touch raw %d,%d -> %d,%d", rx, ry, last_x, last_y);
    }
    data->point.x = last_x;
    data->point.y = last_y;
}

