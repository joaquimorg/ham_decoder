// The analyzer's signal label (status bar) is built in Portuguese without
// accents; its words are swapped here.
static void translate_label(const char *in, char *out, size_t size)
{
    static const char *const WORDS[][3] = {    // analyzer, pt-PT, en
        { "RUIDO", "RUÍDO", "NOISE" }, { "TOM", "TOM", "TONE" }, { "LARGO", "LARGO", "WIDE" },
        { "(voz?)", "(voz?)", "(voice?)" }, { "fase", "fase", "phasing" }, { "VOZ", "VOZ", "VOICE" },
    };
    const int lang = g_settings.language == LANG_EN ? 2 : 1;
    size_t o = 0;
    out[0] = 0;
    while (*in && o + 1 < size) {
        const size_t len = strcspn(in, " ");
        const char *word = nullptr;
        for (const auto &w : WORDS)
            if (strlen(w[0]) == len && !strncmp(in, w[0], len))
                word = w[lang];
        o += snprintf(out + o, size - o, "%.*s", word ? (int)strlen(word) : (int)len, word ? word : in);
        if (o >= size)
            break;
        in += len;
        while (*in == ' ' && o + 1 < size) {
            out[o++] = ' ';
            in++;
        }
        out[o] = 0;
    }
}

