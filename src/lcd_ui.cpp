static void cfg_event(lv_event_t *e)
{
    const CfgId id = (CfgId)(intptr_t)lv_event_get_user_data(e);
    lv_obj_t *obj = (lv_obj_t *)lv_event_get_target(e);
    const lv_event_code_t code = lv_event_get_code(e);
    const bool checked = lv_obj_has_state(obj, LV_STATE_CHECKED);
    bool save = true;
    switch (id) {
    case CFG_CW_AUTO:   g_settings.cw_auto_tone = checked; break;
    case CFG_CONTRAST:
        g_settings.cw_min_contrast = lv_slider_get_value(obj) / 10.0f;
        lv_label_set_text_fmt(lbl_contrast, "%.1f", g_settings.cw_min_contrast);
        save = code == LV_EVENT_RELEASED;
        break;
    case CFG_RTTY_BAUD: g_settings.rtty_baud = RTTY_BAUDS[lv_dropdown_get_selected(obj)]; break;
    case CFG_RTTY_POL:  g_settings.rtty_polarity = lv_dropdown_get_selected(obj); break;
    case CFG_FAX_LPM:   g_settings.fax_lpm = FAX_LPMS[lv_dropdown_get_selected(obj)]; break;
    case CFG_FAX_IOC:   g_settings.fax_ioc = FAX_IOCS[lv_dropdown_get_selected(obj)]; break;
    case CFG_FAX_AUTO:  g_settings.fax_auto = checked; break;
    case CFG_SSTV_ADJ:  g_settings.sstv_adjust = checked; break;
    case CFG_FTX_MODE:  g_settings.ftx_mode = lv_dropdown_get_selected(obj); break;
    case CFG_BRIGHT:
        g_settings.lcd_brightness = lv_slider_get_value(obj);
        lv_label_set_text_fmt(lbl_bright, "%d %%", g_settings.lcd_brightness);
        backlight_set(g_settings.lcd_brightness);
        save = code == LV_EVENT_RELEASED;
        break;
    case CFG_WEB:
        g_settings.web_enabled = checked;
        lv_label_set_text(lbl_web_note, tr(S_CFG_WEB_NOTE));
        break;
    case CFG_LANGUAGE:
        g_settings.language = lv_dropdown_get_selected(obj) ? LANG_EN : LANG_PT;
        lv_async_call(rebuild_ui, nullptr);    // not from inside this widget's own event
        break;
    }
    settings_apply();
    if (save)
        settings_save();
}

