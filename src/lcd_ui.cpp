static FtxMessage ftx_list[FTX_ROWS];    // newest first
static int ftx_count = 0;
static uint32_t ftx_seq = 0;

static void update_ftx()
{
    static FtxMessage fresh[UI_FTX_RING];
    const int n = ui_get_ftx(ftx_seq, fresh, &ftx_seq);
    if (n > 0) {
        const int add = n < FTX_ROWS ? n : FTX_ROWS;
        const int keep = ftx_count + add > FTX_ROWS ? FTX_ROWS - add : ftx_count;
        memmove(ftx_list + add, ftx_list, keep * sizeof(FtxMessage));
        for (int i = 0; i < add; i++)
            ftx_list[i] = fresh[n - 1 - i];
        ftx_count = keep + add;
        lv_table_set_row_count(ftx_table, ftx_count + 1);
        for (int i = 0; i < ftx_count; i++) {
            const FtxMessage &m = ftx_list[i];
            const time_t t = (time_t)m.slot_start;
            struct tm tm;
            gmtime_r(&t, &tm);
            char s[16];
            snprintf(s, sizeof(s), "%02d%02d%02d", tm.tm_hour, tm.tm_min, tm.tm_sec);
            lv_table_set_cell_value(ftx_table, i + 1, 0, s);
            snprintf(s, sizeof(s), "%.0f", m.snr_db);
            lv_table_set_cell_value(ftx_table, i + 1, 1, s);
            snprintf(s, sizeof(s), "%.1f", m.dt);
            lv_table_set_cell_value(ftx_table, i + 1, 2, s);
            snprintf(s, sizeof(s), "%.0f", m.freq_hz);
            lv_table_set_cell_value(ftx_table, i + 1, 3, s);
            lv_table_set_cell_value(ftx_table, i + 1, 4, m.text);
        }
    }
    char s[128];
    const int last = ftx_last_count();
    if (g_settings.ftx_mode == FTX_OFF)
        snprintf(s, sizeof(s), "%s", tr(S_FTX_OFF));
    else if (!ftx_time_ok())
        snprintf(s, sizeof(s), LV_SYMBOL_WARNING " %s", tr(S_FTX_NO_TIME));
    else if (last >= 0)
        snprintf(s, sizeof(s), tr(S_FTX_LAST), last, ftx_last_ms());
    else
        snprintf(s, sizeof(s), "%s", tr(S_FTX_WAIT));
    lv_label_set_text(lbl_ftx_state, s);
}

