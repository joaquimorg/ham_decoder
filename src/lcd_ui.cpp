// Language change: the widgets are made again in the new language, and the
// text, FT8 list and image are fetched again from ui_hub.
static void rebuild_ui(void *)
{
    settings_save();
    lv_obj_clean(lv_display_get_screen_active(display));
    for (TextView &tv : text_views) {
        tv.seq = 0;
        tv.len = 0;
        tv.tail[0] = 0;
    }
    ftx_count = 0;
    ftx_seq = 0;
    img_drawn_id = 0;
    build_ui();
    lv_tabview_set_active(tabview, 4, LV_ANIM_OFF);    // back in the settings
}

void lcd_ui_start()
{
    backlight_init();
    esp_lcd_panel_io_handle_t io;
    esp_lcd_panel_handle_t panel;
    panel_init(&io, &panel);
    touch_init();

    lvgl_port_cfg_t port_cfg = ESP_LVGL_PORT_INIT_CONFIG();
    port_cfg.task_priority = 3;
    port_cfg.task_affinity = LCD_TASK_CORE;
    port_cfg.task_stack = 8192;
    ESP_ERROR_CHECK(lvgl_port_init(&port_cfg));

    lvgl_port_display_cfg_t disp_cfg = {};
    disp_cfg.io_handle = io;
    disp_cfg.panel_handle = panel;
    disp_cfg.buffer_size = LCD_H_RES * 20;    // x2, DMA-capable internal RAM (scarce)
    disp_cfg.double_buffer = true;
    disp_cfg.hres = LCD_H_RES;
    disp_cfg.vres = LCD_V_RES;
    disp_cfg.monochrome = false;
    disp_cfg.color_format = LV_COLOR_FORMAT_RGB565;
    disp_cfg.rotation.swap_xy = true;       // landscape (MADCTL MV, as TFT_eSPI rotation 1)
    disp_cfg.rotation.mirror_x = false;
    disp_cfg.rotation.mirror_y = false;
    disp_cfg.flags.buff_dma = true;
    disp_cfg.flags.swap_bytes = true;       // RGB565 goes out big endian
    display = lvgl_port_add_disp(&disp_cfg);

    lvgl_port_lock(0);
    lv_indev_t *indev = lv_indev_create();
    lv_indev_set_type(indev, LV_INDEV_TYPE_POINTER);
    lv_indev_set_read_cb(indev, touch_read_cb);
    lv_indev_set_display(indev, display);
    lv_display_set_theme(display, lv_theme_default_init(display, lv_palette_main(LV_PALETTE_BLUE),
                                                        lv_palette_main(LV_PALETTE_RED), true, &font_ui_14));
    build_lut();
    build_ui();
    lv_timer_create(ui_timer, 50, nullptr);
    lvgl_port_unlock();

    backlight_set(g_settings.lcd_brightness);
    ESP_LOGI(TAG, "LCD %dx%d ST7796 + touch FT6336U, RAM interna livre %u KB", LCD_H_RES, LCD_V_RES,
             (unsigned)(heap_caps_get_free_size(MALLOC_CAP_INTERNAL) / 1024));
}

